@dataclass
class MortalConfig:
    """Configuration for Mortal-style V5 value learning."""

    # -- schedule --
    total_steps: int = 1_000_000
    """Total *learner decisions* collected across the whole run."""
    rollout_steps: int = 8192
    """Learner decisions collected per optimisation round."""
    n_envs: int = 8
    n_epochs: int = 2
    batch_size: int = 256
    max_seq_len: int = 512

    # -- optimisation --
    gamma: float = 0.99
    lr: float = 1e-4
    grad_clip: float = 1.0
    weight_decay: float = 0.0
    huber_delta: float = 0.0
    """If ``>0`` use a Huber (smooth-L1) DQN loss with this ``beta`` instead
    of ``0.5*MSE``.  Huber caps the per-sample gradient at ``1`` once the
    error exceeds ``huber_delta``, so the huge initial TD error of a BC
    warm-start (``q~-20`` vs target ``~0``) no longer crushes the BC policy
    scale in the first update -- essential for the BC anchor to hold.  ``0``
    (default) keeps the original ``0.5*MSE``."""

    # -- Mortal loss weights --
    cql_enable: bool = False
    """Enable the CQL conservatism term.  Off by default for online
    self-play (matches Mortal's online mode); turn on for offline/static
    data to suppress OOD-action Q over-estimation."""
    min_q_weight: float = 1.0
    """Weight of the CQL term (only used when ``cql_enable``)."""
    next_rank_weight: float = 0.5
    """Weight of the auxiliary final-rank cross-entropy."""
    bc_anchor_weight: float = 0.0
    """Weight of the KL/CE-to-frozen-BC **policy anchor**.  ``>0`` adds a
    cross-entropy of the learner's Q-derived policy against the frozen BC
    policy (soft labels) -- i.e. forward ``KL(BC || learner)`` up to a
    constant -- which keeps the BC *action ordering* intact independently of
    the (collapsing) absolute Q scale.  This is the anti-collapse fix for BC
    warm-starts; CQL cannot do it because CQL anchors to the *current*
    behaviour, not BC.  ``0`` disables.  Needs a BC reference: the fixed-BC
    opponent is reused, else one is built from ``opponent_bc_checkpoint`` /
    the warm-started learner."""

    # -- reward shaping (GRP / placement) --
    reward_kind: str = "points"
    """``"points"`` (default, raw per-kyoku score delta in 25k units),
    ``"placement"`` (deterministic provisional placement, no extra net), or
    ``"grp"`` (needs a trained GRP checkpoint)."""
    grp_ckpt: Optional[str] = None
    """Path to a trained GRP checkpoint; required for ``reward_kind='grp'``."""
    grp_hidden: int = 64
    grp_layers: int = 2
    pts: Tuple[float, float, float, float] = (3.0, 1.0, -1.0, -3.0)
    reward_clip: float = 0.0
    """Symmetric clip on the per-decision Q-target (``<=0`` disables)."""

    # -- exploration during collection --
    epsilon: float = 0.0
    """Probability of a uniform random legal action during self-play
    collection.  ``0`` = pure greedy.  Small values (0.02-0.1) add
    exploration without a separate stochastic policy."""
    collect_stochastic: bool = False
    """If True, sample actions from a Boltzmann softmax over Q during
    collection instead of argmax (separate from ``epsilon``)."""

    # -- opponents: fixed frozen-BC environment (default) --
    fixed_bc_opponents: bool = True
    """If True (default), the 3 non-learner seats are a FROZEN BC model and
    only the single learner seat is trained.  The learner seat rotates
    ``0->1->2->3`` across hanchan for balanced seat / round-wind / dealer
    coverage.  Against a stationary BC reference the points/placement reward
    is no longer zero-sum-symmetric (the learner can out-earn the fixed BC),
    which gives a real improvement gradient -- unlike symmetric self-play,
    whose expected per-seat reward is ~0.  When False, fall back to the
    historical self-play opponent pool below."""
    opponent_bc_checkpoint: Optional[str] = None
    """BC checkpoint for the 3 frozen opponents in fixed-BC mode.  ``None``
    (default) reuses the learner's own warm-start ``bc_checkpoint``."""

    # -- self-play / opponent pool (only used when fixed_bc_opponents=False) --
    opponent_mix_ratio: float = 0.25
    n_frozen_seats: int = 1
    snapshot_interval: int = 50_000
    pool_capacity: int = 20
    pool_sampling: str = "pfsp"
    pfsp_p: float = 2.0

    # -- I/O --
    save_path: str = "checkpoints/mortal_v5.pt"
    """Path of the rolling "latest" checkpoint (overwritten each save)."""
    save_interval: int = 100_000
    """Save (and, if enabled, Mortal-eval) every this many learner steps."""
    keep_periodic: bool = True
    """If True, *also* persist a per-step copy ``<save_path stem>.step_<N>.pt``
    at every save so historical checkpoints are retained (not just the
    overwritten ``save_path``)."""
    snapshot_dir: Optional[str] = None

    # -- misc --
    device: Optional[str] = None
    seed: Optional[int] = None
    log_interval: int = 1

    # -- architecture (must match the BC ckpt) --
    scorer_hidden: int = 256
    action_proj_dim: Optional[int] = None

    # -- wandb (optional) --
    wandb_project: Optional[str] = None
    wandb_entity: Optional[str] = None
    wandb_name: Optional[str] = None
    wandb_tags: Optional[Tuple[str, ...]] = None
    wandb_mode: str = "online"

    # -- Mortal head-to-head eval on every checkpoint save (1v3 + 3v1) --
    # Disabled by default.  When enabled, after each checkpoint is written
    # the trainer exports a V5-compatible (DouzeroV5Transformer-layout)
    # checkpoint and runs ``mjai_bench_v2`` as a subprocess for two
    # matchups (1v3 and 3v1) vs the Mortal AI, logging ``mortal/*`` to
    # wandb.  All paths are server-specific and must be supplied.
    mortal_eval: bool = False
    """Enable Mortal head-to-head eval after each checkpoint save."""
    mortal_eval_hanchan: int = 1000
    """Hanchan per matchup.  More = lower variance but longer pause.
    1000 gives a very tight estimate (rank std-err ~0.035); with
    ``mortal_eval_workers`` 8 it finishes in a few tens of minutes.  For
    fast in-training periodic eval override this back to a small value
    (e.g. 16-64)."""
    mortal_eval_workers: int = 1
    """Concurrent bench processes per matchup (splits n_hanchan; the bench is
    latency-bound with low GPU util, so 4-8 ~ linear eval speedup)."""
    mortal_bench_script: Optional[str] = None
    """Absolute path to the ``mjai_bench_v2.py`` benchmark CLI."""
    mortal_bench_cwd: Optional[str] = None
    """Working directory for the bench subprocess (its src/ dir)."""
    mortal_ckpt: Optional[str] = None
    """Absolute path to the Mortal ``.pth`` weights (e.g. mortal_298k.pth)."""
    mortal_eval_python: Optional[str] = None
    """Interpreter for the eval subprocess.  ``None`` = ``sys.executable``."""
    mortal_eval_out_dir: Optional[str] = None
    """Root dir for per-step eval logs.  ``None`` = ``<save_path dir>/mortal_eval``."""
    mortal_eval_seed_start: int = 10000
    mortal_eval_seed_key: int = 4242
    mortal_eval_timeout_sec: float = 1800.0
    mortal_eval_amp: bool = False



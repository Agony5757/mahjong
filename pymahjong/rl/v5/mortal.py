"""Mortal-style value-learning trainer for the V5 network.

This implements Mortal's reinforcement-learning algorithm (value-based,
*not* PPO) on top of this project's V5 components:

* The state is encoded by the unmodified ``EventStreamTransformer`` and a
  Douzero per-legal-action scorer **outputs ``Q(s, a)`` directly** (see
  :class:`~pymahjong.rl.v5.mortal_qnet.MortalQNet`).
* **Monte-Carlo Q target** per Mortal::

      q_target = gamma ** steps_to_done * kyoku_reward

  where ``steps_to_done`` is the number of the seat's *own* remaining
  decisions until the end of the kyoku and ``kyoku_reward`` is that
  kyoku's placement reward (see :mod:`pymahjong.rl.v5.grp`).
* **DQN loss** ``0.5 * MSE(q_taken, q_target)``.
* **CQL regulariser** (optional, Mortal's offline conservatism)
  ``min_q_weight * (logsumexp_a q - q_taken)``.
* **Auxiliary next-rank head** ``next_rank_weight * CE(aux_logits, final_rank)``.

Data is generated by **full-hanchan play** using
:class:`~pymahjong.rl.v4.hanchan_env.HanchanEnv`, which yields the
per-kyoku score sequence + final ranks needed for the reward.  By
**default** the 3 non-learner seats are a *frozen BC model* and only the
single (rotating) learner seat is trained: against this stationary
reference the points/placement reward is no longer zero-sum-symmetric, so
there is a real improvement gradient.  Set ``fixed_bc_opponents=False`` to
fall back to symmetric self-play with an
:class:`~pymahjong.rl.v4.opponent_pool.OpponentPool` of frozen historical
snapshots (the original behaviour, like the PPO path).

Unlike PPO, the update runs in ``train()`` mode (dropout on): the target
is a Monte-Carlo regression, not an importance-sampled ratio, so there is
no behaviour/target policy-consistency requirement.
"""

from __future__ import annotations

import os
import time
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

try:
    import torch
    import torch.nn.functional as F
except Exception as e:  # noqa: BLE001
    raise RuntimeError("torch is required for Mortal-style V5 training") from e

from ..common.config import TransformerConfig
from ..v4.hanchan_env import HanchanEnv
from ..v4.opponent_pool import OpponentPool
